"""Extract CUDA objective expressions; replace only their math primitives.

Generated code runs the vendored expressions on the host with either native
FP32 libm or binary64 libm rounded to FP32. It is not NVIDIA execution.
"""
from pathlib import Path
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]


def body(source, start):
    opening = source.index("{", start)
    end, depth = opening + 1, 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[opening:end]


def primitives(text):
    for old, new in [("common::Sigmoid(", "Sigmoid("),
                     ("common::SoftPlus(", "SoftPlus("),
                     ("common::Sqr(", "xgboost::common::Sqr("),
                     ("std::log1p(", "Math::Log1p("), ("std::exp(", "Math::Exp("),
                     ("expf(", "Math::Exp("), ("std::sqrt(", "Math::Sqrt("),
                     ("std::pow(", "Math::Pow("), ("fmaxf(", "Math::FMax(")]:
        text = text.replace(old, new)
    return text


def main():
    paths = ["common/math.h", "objective/regression_loss.h",
             "objective/regression_obj.cu", "objective/hinge.cu", "objective/quantile_obj.cu"]
    sources = [(ROOT / "xgboost/src" / p).read_text() for p in paths]
    math, losses, regression, hinge, quantile = sources
    parts = ["// Generated by tests/build_objective_reference.py from vendored CUDA sources."]
    parts += [f"// SHA256 {p}: {hashlib.sha256(s.encode()).hexdigest()}" for p, s in zip(paths, sources)]
    parts += ["#pragma once", '#include "../xgboost/src/common/math.h"',
              "#include <vector>", "namespace objective_reference {", "using xgboost::GradientPair;",
              "using xgboost::kRtEps;", "template <class Math> struct Ref {"]
    parts += ["static float Sigmoid(float x) " + primitives(body(math, math.index("inline float Sigmoid(float x)"))),
              "static float SoftPlus(float x) " + primitives(body(math, math.index("SoftPlus(F x)")))]
    names = ["LinearSquareLoss", "LogisticRegression", "SquaredLogError", "GammaDeviance"]
    for name in names:
        source = body(losses, losses.index(name + " {"))
        parts.append(f"struct {name} {{")
        for method in ["PredTransform", "FirstOrderGradient", "SecondOrderGradient"]:
            match = re.search(r"XGBOOST_DEVICE static (?:bst_float|float) " + method + r"\([^)]*\)", source)
            assert match, (name, method)
            signature = match.group().replace("XGBOOST_DEVICE ", "").replace("bst_float", "float")
            parts.append(signature + " " + primitives(body(source, match.start())))
        parts.append("};")
    parts.append('''template <class Loss> static GradientPair Generic(float raw, float label, float w, float scale) {
      float p = Loss::PredTransform(raw);
      if (label == 1.0f) w *= scale;
      return {Loss::FirstOrderGradient(p, label) * w, Loss::SecondOrderGradient(p, label) * w};
    }
    static GradientPair Pair(unsigned kind, std::vector<float> const& preds,
        std::vector<float> const& ys, std::vector<float> const& weights,
        std::vector<float> const& alpha, unsigned targets, unsigned label_targets,
        std::size_t i, std::size_t j, float parameter, float scale) {
      auto predt = [&](std::size_t row, std::size_t target) { return preds[row * targets + target]; };
      auto labels = [&](std::size_t row, std::size_t target) { return ys[row * label_targets + (label_targets == 1 ? 0 : target)]; };
      struct Weights { std::vector<float> const& v; float operator[](std::size_t row) const { return v.empty() ? 1.f : v[row]; } } weight{weights};
      auto const& sample_weights = weight;
      float slope = parameter, max_delta_step = parameter, rho = parameter;
      auto n_alphas = targets;
      GradientPair result;
      switch (kind) {''')
    for kind, name in enumerate(names):
        # Squared-log's specialized class has no scale_pos_weight parameter.
        parts.append(f"case {kind}: return Generic<{name}>(predt(i,j), labels(i,j), weight[i], {'1.f' if kind == 2 else 'scale'});")
    for kind, name, source in [(4, "PseudoHuberRegression", regression),
                               (5, "PoissonRegression", regression),
                               (6, "TweedieRegression", regression),
                               (7, "HingeObj", hinge), (9, "ExpectileRegression", regression)]:
        start = source.index("class " + name + " :")
        match = re.search(r"XGBOOST_DEVICE\(std::size_t i, std::size_t j\) mutable", source[start:])
        assert match, name
        expr = body(source, start + match.start())[1:-1]
        expr = expr.replace("gpair(i, j)", "result").replace("weights[i]", "sample_weights[i]")
        parts.append(f"case {kind}: {{\n" + primitives(expr) + "\nreturn result;\n}")
    parts += ["} return result; }"]
    # The quantile transform's loop itself is source, including NaN barriers.
    start = quantile.index("void PredTransform(")
    start = quantile.index("XGBOOST_DEVICE(std::size_t row", start)
    loop = body(quantile, start)
    parts.append("static void Quantile(std::vector<float>& predts, std::size_t row, unsigned n_alphas) " + loop)
    parts += ["};", "}  // namespace objective_reference", ""]
    target = ROOT / "results/cuda_objective_reference_generated.h"
    target.write_text("\n".join(parts))
    print(f"Generated {target.relative_to(ROOT)} from {len(paths)} vendored source files")


if __name__ == "__main__":
    main()
