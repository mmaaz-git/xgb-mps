// Portable inputs and explicit numerical-policy witnesses for Metal/NVIDIA runs.
// Alternative results describe an order, never a measured NVIDIA result.
#pragma once
#include <cmath>
#include <cstdint>
#include <vector>

namespace numerical_contracts {
inline float Add(float a, float b) {
  volatile float rounded = a + b;
  return rounded;
}
struct Quantile {
  std::vector<float> values, weights, serial, regrouped;
};
inline Quantile MakeQuantile(unsigned rows, int exponent) {
  float small = std::ldexp(1.f, exponent), large = std::ldexp(0x1p24f, exponent);
  Quantile q;
  q.values.resize(rows);
  q.weights.resize(rows);
  for (unsigned i = 0; i < rows; ++i) q.values[i] = float(i);
  q.weights[0] = large;
  q.weights[rows - 2] = q.weights[rows - 1] = small;
  float sum = 0;
  for (float w : q.weights) q.serial.push_back(sum = Add(sum, w));
  q.regrouped = q.serial;
  // At alpha=1 the threshold is exactly the FP32 total in binary64, isolating
  // association from the separate NUM-1 threshold-narrowing defect.
  q.regrouped.back() = Add(large, Add(small, small));
  return q;
}
struct Prefix {
  std::vector<float> values, metal, serial;
  std::vector<std::uint32_t> ids;
};
inline Prefix MakePrefix(unsigned rows, int exponent) {
  float small = std::ldexp(1.f, exponent), large = std::ldexp(0x1p24f, exponent);
  Prefix p;
  for (unsigned i = 0; i < rows; ++i) {
    unsigned start = i - i % 3;
    p.ids.push_back(i / 3);
    p.values.push_back(i % 3 ? small : large);
    p.serial.push_back(large);  // Each sequential large+small addition rounds down.
    // Explicit three-element witnesses, not an emulation of the scan kernel:
    // when the final small term starts a new tile, the preceding tile has
    // already lost the first small term. Otherwise the two smalls combine first.
    bool lost_at_tile_boundary = start % 256 == 254;
    p.metal.push_back(i % 3 == 2 && !lost_at_tile_boundary
                          ? Add(large, Add(small, small)) : large);
  }
  return p;
}
struct Entry {
  float rmin, rmax, wmin, value;
};
static_assert(sizeof(Entry) == 16);
struct Summary {
  std::vector<Entry> input, metal, alternative;
  std::vector<std::uint64_t> ptr;
};
inline Summary MakeReverse(int exponent) {
  float s = std::ldexp(1.f, exponent), b = std::ldexp(0x1p24f, exponent);
  float total = Add(b, Add(s, s));
  Summary r;
  // Empty column, real duplicate values, a value boundary, and equal-rank
  // pruning duplicates. Only the first duplicate kind accumulates its weight.
  r.ptr = {0, 0, 3, 6, 9};
  r.input = {{0, s, s, 7}, {s, 2*s, s, 7}, {2*s, total, b, 7},
             {0, s, s, 11}, {s, 2*s, s, 12}, {2*s, total, b, 12},
             {0, s, s, 7}, {0, s, s, 7}, {2*s, total, b, 7}};
  r.metal = {{0, b, b, 7}, {s, b, b, 7}, {2*s, total, b, 7},
             {0, s, s, 11}, {s, b, b, 12}, {2*s, total, b, 12},
             {0, s, s, 7}, {0, b, b, 7}, {2*s, total, b, 7}};
  r.alternative = r.metal;
  // The source reverse-scan operator can group the left two small weights
  // before combining the right large weight. Record that first result only.
  r.alternative[0] = {0, total, total, 7};
  return r;
}
inline Summary MakeRepair(int exponent) {
  float s = std::ldexp(1.f, exponent);
  Summary r;
  r.ptr = {0, 0, 4, 5, 9};
  // Synthetic rank violations isolate neighboring reads. They are not a claim
  // that this exact array is generated by a valid training dataset.
  r.input = {{8*s, 9*s, s, 0}, {4*s, 5*s, s, 1}, {2*s, 3*s, s, 2}, {0, s, s, 3},
             {-2*s, -s, 2*s, 9},
             {8*s, 9*s, s, 0}, {4*s, 5*s, s, 1}, {2*s, 3*s, s, 2}, {0, s, s, 3}};
  r.metal = r.input;
  r.alternative = r.input;
  for (unsigned base : {0u, 5u}) {
    for (unsigned i = 0; i < 4; ++i) r.metal[base+i] = {8*s, 9*s, s, float(i)};
    r.alternative[base+1] = {8*s, 9*s, s, 1};
    r.alternative[base+2] = {4*s, 5*s, s, 2};
    r.alternative[base+3] = {2*s, 3*s, s, 3};
  }
  r.metal[4] = r.alternative[4] = {0, 2*s, 2*s, 9};
  // alternative: right-to-left updates see unrepaired predecessors. This is
  // an illustrative source ordering, not a prediction of a CUDA race winner.
  return r;
}
}  // namespace numerical_contracts
